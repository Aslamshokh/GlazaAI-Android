for rel, old, new in BUNDLE["patches"]:
    p = pathlib.Path(rel)
    if not p.exists():
        print("нет файла:", rel); bad += 1; continue
    t = p.read_text(encoding="utf-8")
    if new in t:
        skip += 1; continue
    if t.count(old) != 1:
        print("не найдено место в", rel, "->", old.strip().splitlines()[0][:70]); bad += 1; continue
    p.write_text(t.replace(old, new), encoding="utf-8"); done += 1

